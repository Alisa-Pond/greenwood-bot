import threading
import time
from datetime import datetime
from zoneinfo import ZoneInfo

from services.summary import send_daily_summaries


# =========================================================
# НАЛАШТУВАННЯ
# =========================================================

KYIV_TZ = ZoneInfo("Europe/Kyiv")

SUMMARY_HOUR = 7
SUMMARY_MINUTE = 0


# =========================================================
# ПЕРЕВІРКА ЧАСУ
# =========================================================

def is_summary_time():
    """
    Перевіряє, чи зараз 07:00 за київським часом.
    """

    now = datetime.now(KYIV_TZ)

    return (
        now.hour == SUMMARY_HOUR
        and now.minute == SUMMARY_MINUTE
    )


# =========================================================
# ЦИКЛ ПЛАНУВАЛЬНИКА
# =========================================================

def scheduler_loop():
    """
    Постійно перевіряє київський час.

    О 07:00 запускає формування та надсилання
    щоденних підсумків за попередню добу.

    Планувальник перевіряє час кожні 20 секунд.
    """

    # Захист від повторного запуску протягом
    # одного процесу бота.
    last_attempt_date = None

    print("⏰ Планувальник підсумків запущено.")
    print("🌲 Часова зона: Europe/Kyiv")
    print("🌅 Щоденні підсумки: 07:00")

    while True:

        try:

            now = datetime.now(KYIV_TZ)

            current_date = now.date()

            # =================================================
            # ЧИ НАСТАВ ЧАС ПІДСУМКІВ?
            # =================================================

            if is_summary_time():

                # Не запускаємо summary повторно
                # протягом цього дня.
                if last_attempt_date != current_date:

                    print(
                        "🌅 Настав час ранкових хронік: "
                        f"{now.strftime('%d.%m.%Y %H:%M:%S')}"
                    )

                    try:

                        # =====================================
                        # ФОРМУВАННЯ ТА НАДСИЛАННЯ ПІДСУМКІВ
                        # =====================================

                        send_daily_summaries()

                        print(
                            "✅ Щоденні підсумки успішно "
                            "сформовано та відправлено."
                        )

                    except Exception as error:

                        print(
                            "❌ Помилка під час формування "
                            "або відправлення підсумків:"
                        )

                        print(error)

                    finally:

                        # Навіть якщо одному користувачу
                        # не вдалося відправити повідомлення,
                        # не запускаємо весь summary десятки разів
                        # протягом однієї ранкової хвилини.
                        last_attempt_date = current_date

            # =================================================
            # ПЕРЕВІРКА КОЖНІ 20 СЕКУНД
            # =================================================

            time.sleep(20)

        except Exception as error:

            print(
                "❌ Критична помилка планувальника:"
            )

            print(error)

            # Scheduler не повинен вбивати
            # основний процес бота.

            time.sleep(30)


# =========================================================
# ЗАПУСК У ФОНОВОМУ ПОТОЦІ
# =========================================================

def start_scheduler():
    """
    Запускає планувальник в окремому daemon-потоці.
    """

    thread = threading.Thread(
        target=scheduler_loop,
        daemon=True,
        name="GreenwoodScheduler"
    )

    thread.start()

    print(
        "🌲 Фоновий планувальник Грінвуду працює."
    )

    return thread
