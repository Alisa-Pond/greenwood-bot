import threading
import time
from datetime import datetime
from zoneinfo import ZoneInfo

from services.summary import send_daily_summaries
from services.database import get_all_players

from handlers.my_quests.expedition.timer import (
    check_expedition_reminder
)


# =========================================================
# НАЛАШТУВАННЯ
# =========================================================

KYIV_TZ = ZoneInfo("Europe/Kyiv")

SUMMARY_HOUR = 7
SUMMARY_MINUTE = 0

# Перевірка scheduler кожні 30 секунд
CHECK_INTERVAL = 30


# =========================================================
# ПЕРЕВІРКА, ЧИ НАСТАВ ЧАС ПІДСУМКУ
# =========================================================

def is_summary_time():
    """
    Перевіряє, чи настав час щоденного підсумку.

    Підсумок дозволено відправляти о 07:00 або пізніше,
    якщо бот був перезапущений після 07:00.
    """

    now = datetime.now(KYIV_TZ)

    return (
        now.hour > SUMMARY_HOUR
        or (
            now.hour == SUMMARY_HOUR
            and now.minute >= SUMMARY_MINUTE
        )
    )


# =========================================================
# ПЕРЕВІРКА ЕКСПЕДИЦІЙ
# =========================================================

def check_expeditions():
    """
    Перевіряє активні експедиції всіх користувачів.

    Якщо експедиція триває достатньо довго,
    timer.py надсилає нагадування Генерала Мурахи.

    Перевірка виконується окремо для кожного користувача,
    тому дані однієї експедиції не можуть змішатися
    з даними іншої.
    """

    try:

        players = get_all_players()

        if not players:
            return

        for player in players:

            try:

                check_expedition_reminder(
                    player
                )

            except Exception as error:

                user_id = player.get(
                    "user_id",
                    "невідомий"
                )

                print(
                    "❌ Помилка перевірки "
                    f"експедиції користувача {user_id}: "
                    f"{error}"
                )

    except Exception as error:

        print(
            "❌ Помилка отримання гравців "
            f"для перевірки експедицій: {error}"
        )


# =========================================================
# ЦИКЛ ПЛАНУВАЛЬНИКА
# =========================================================

def scheduler_loop():
    """
    Постійно перевіряє київський час.

    Scheduler виконує дві незалежні функції:

    1. Після 07:00 формує щоденні підсумки.
    2. Кожні 30 секунд перевіряє експедиції
       та нагадує про них після кожних 60 хв
       активного часу.

    Один і той самий ранковий підсумок
    не відправляється повторно в межах
    одного запуску бота.
    """

    last_summary_date = None

    print(
        "⏰ Планувальник Грінвуду запущено."
    )

    print(
        "🌲 Часова зона: Europe/Kyiv"
    )

    print(
        "🌅 Щоденні підсумки: після 07:00"
    )

    print(
        "🐜 Перевірка експедицій: кожні 30 секунд"
    )

    while True:

        try:

            now = datetime.now(
                KYIV_TZ
            )

            current_date = now.date()

            # =================================================
            # ЕКСПЕДИЦІЇ
            # =================================================
            #
            # Перевіряємо їх кожні 30 секунд.
            #
            # Сам timer.py визначає,
            # чи настав момент для нагадування.
            #
            # =================================================

            try:

                check_expeditions()

            except Exception as error:

                print(
                    "❌ Помилка перевірки експедицій: "
                    f"{error}"
                )

            # =================================================
            # ЩОДЕННИЙ SUMMARY
            # =================================================

            if is_summary_time():

                # -------------------------------------------------
                # Захист від повторного запуску
                # -------------------------------------------------

                if last_summary_date != current_date:

                    print(
                        "🌅 Настав час ранкових хронік: "
                        f"{now.strftime('%d.%m.%Y %H:%M:%S')}"
                    )

                    try:

                        # -------------------------------------------------
                        # Формування та надсилання підсумків
                        # -------------------------------------------------

                        send_daily_summaries()

                        # -------------------------------------------------
                        # Запам'ятовуємо дату тільки після успіху
                        # -------------------------------------------------

                        last_summary_date = current_date

                        print(
                            "✅ Щоденні підсумки "
                            "успішно відправлено."
                        )

                    except Exception as error:

                        print(
                            "❌ Помилка під час "
                            "відправлення щоденних підсумків: "
                            f"{error}"
                        )

                        # Не змінюємо
                        # last_summary_date.
                        #
                        # Планувальник спробує ще раз
                        # під час наступної перевірки.

            # =================================================
            # НАСТУПНА ПЕРЕВІРКА
            # =================================================

            time.sleep(
                CHECK_INTERVAL
            )

        except Exception as error:

            print(
                "❌ Критична помилка "
                f"планувальника: {error}"
            )

            # Не дозволяємо exception
            # вбити background thread.

            time.sleep(
                CHECK_INTERVAL
            )


# =========================================================
# ЗАПУСК У ФОНОВОМУ ПОТОЦІ
# =========================================================

def start_scheduler():
    """
    Запускає планувальник в окремому daemon-потоці.
    """

    thread = threading.Thread(
        target=scheduler_loop,
        daemon=True,
        name="GreenwoodScheduler"
    )

    thread.start()

    print(
        "🌲 Фоновий планувальник Грінвуду працює."
    )

    return thread
