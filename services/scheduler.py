import threading
import time
from datetime import datetime
from zoneinfo import ZoneInfo

from services.summary import send_daily_summaries


# =========================================================
# НАЛАШТУВАННЯ
# =========================================================

KYIV_TZ = ZoneInfo("Europe/Kyiv")

SUMMARY_HOUR = 7
SUMMARY_MINUTE = 0


# =========================================================
# ПЕРЕВІРКА ЧАСУ
# =========================================================

def is_summary_time():
    """
    Перевіряє, чи зараз 07:00 за київським часом.
    """

    now = datetime.now(KYIV_TZ)

    return (
        now.hour == SUMMARY_HOUR
        and now.minute == SUMMARY_MINUTE
    )


# =========================================================
# ЦИКЛ ПЛАНУВАЛЬНИКА
# =========================================================

def scheduler_loop():
    """
    Постійно перевіряє київський час.

    О 07:00 запускає формування та
    надсилання підсумків попередньої
    доби Грінвуду.

    Після успішного запуску запам'ятовує
    дату, щоб не відправити підсумок
    повторно.
    """

    last_summary_date = None

    print("⏰ Планувальник підсумків запущено.")
    print("🌲 Часова зона: Europe/Kyiv")
    print("🌅 Щоденні підсумки: 07:00")

    while True:

        try:

            now = datetime.now(KYIV_TZ)

            current_date = now.date()

            # -------------------------------------------------
            # Чи настав час підсумків?
            # -------------------------------------------------

            if (
                now.hour == SUMMARY_HOUR
                and now.minute == SUMMARY_MINUTE
            ):

                # -------------------------------------------------
                # Захист від повторного запуску
                # -------------------------------------------------

                if last_summary_date != current_date:

                    print(
                        "🌅 Настав час ранкових хронік: "
                        f"{now.strftime('%d.%m.%Y %H:%M:%S')}"
                    )

                    try:

                        # -------------------------------------------------
                        # Формування та надсилання всіх підсумків
                        # -------------------------------------------------

                        send_daily_summaries()

                        # -------------------------------------------------
                        # Запам'ятовуємо дату тільки після успіху
                        # -------------------------------------------------

                        last_summary_date = current_date

                        print(
                            "✅ Щоденні підсумки успішно відправлено."
                        )

                    except Exception as error:

                        print(
                            "❌ Помилка під час відправлення "
                            f"щоденних підсумків: {error}"
                        )

                        # ВАЖЛИВО:
                        # last_summary_date НЕ змінюємо.
                        #
                        # Якщо відправка не вдалася, scheduler
                        # зможе повторити спробу в межах цієї
                        # хвилини.

            # -------------------------------------------------
            # Перевіряємо час кожні 20 секунд
            # -------------------------------------------------

            time.sleep(20)

        except Exception as error:

            print(
                "❌ Критична помилка планувальника: "
                f"{error}"
            )

            # Не дозволяємо одному exception
            # вбити весь background thread.

            time.sleep(30)


# =========================================================
# ЗАПУСК У ФОНОВОМУ ПОТОЦІ
# =========================================================

def start_scheduler():
    """
    Запускає планувальник в окремому daemon-потоці.
    """

    thread = threading.Thread(
        target=scheduler_loop,
        daemon=True,
        name="GreenwoodScheduler"
    )

    thread.start()

    print(
        "🌲 Фоновий планувальник Грінвуду працює."
    )

    return thread
