@bot.message_handler(
    func=lambda message:
        message.text == "🌲 Продовжити шлях"
)
def continue_chapter1(
    message
):

    user_id = str(
        message.from_user.id
    )

    player = get_player(
        user_id
    )

    if not player:

        bot.send_message(
            message.chat.id,
            "🌲 Не вдалося знайти твого персонажа."
        )

        return

    main_quest = (
        player.get(
            "main_quest"
        )
        or {}
    )

    current_task = (
        main_quest.get(
            "current_task"
        )
    )

    # =====================================================
    # НЕМАЄ ПОТОЧНОГО ЗАВДАННЯ
    # =====================================================

    if not current_task:

        show_chapter1(
            message,
            player
        )

        return

    task_id = current_task.get(
        "id"
    )

    # =====================================================
    # ПЕРЕВІРКА 5 XP ЗДОРОВ'Я
    # =====================================================

    if task_id == TASK_HEALTH:

        health_xp = get_sphere_xp(
            player,
            "health"
        )

        if health_xp < HEALTH_TARGET_XP:

            remaining = (
                HEALTH_TARGET_XP
                - health_xp
            )

            bot.send_message(
                message.chat.id,

                "🌲 <b>Стежка поки не відкривається. "
                f"Тобі ще потрібно отримати {remaining:g} XP "
                "у сфері 💪 Здоров'я.</b>",

                parse_mode="HTML",

                reply_markup=get_chapter_keyboard()
            )

            return

        # -------------------------------------------------
        # ДОСТАТНЬО XP
        # -------------------------------------------------

        set_current_task(
            player,
            TASK_BEATRICE,
            progress=0,
            required=1,
            target="beatrice"
        )

        add_completed_scene(
            player,
            TASK_HEALTH
        )

        save_main_quest(
            user_id,
            player
        )

        send_message_4(
            message
        )

        time.sleep(2)

        send_message_5(
            message
        )

        time.sleep(4)

        set_current_task(
            player,
            TASK_LEAF,
            progress=0,
            required=1,
            target="blue_leaf"
        )

        add_completed_scene(
            player,
            TASK_BEATRICE
        )

        save_main_quest(
            user_id,
            player
        )

        send_message_6(
            message
        )

        return

    # =====================================================
    # СИНІЙ ЛИСТОК
    # =====================================================

    if task_id == TASK_LEAF:

        inventory = (
            player.get(
                "inventory"
            )
            or []
        )

        # -------------------------------------------------
        # ПЕРЕВІРЯЄМО, ЧИ ЛИСТОК ВЖЕ В ІНВЕНТАРІ
        # -------------------------------------------------

        leaf_already_added = False

        for item in inventory:

            item_text = str(
                item
            )

            if (
                "Синій листок"
                in item_text
            ):

                leaf_already_added = True

                break

        # -------------------------------------------------
        # ДОДАЄМО ЛИСТОК
        # -------------------------------------------------

        if not leaf_already_added:

            give_blue_leaf(
                player
            )

        finish_chapter_1(
            message,
            player
        )

        return

    # =====================================================
    # НЕВІДОМИЙ СТАН
    # =====================================================

    show_chapter1(
        message,
        player
    )


