# ВСТАНОВИТИ ПОТОЧНЕ ЗАВДАННЯ
# =========================================================

def set_current_task(
    player,
    task_id,
    progress=0,
    required=0,
    target=None
):

    main_quest = (
        player.get(
            "main_quest"
        )
        or {}
    )

    main_quest[
        "chapter"
    ] = CHAPTER

    main_quest[
        "current_task"
    ] = {

        "id":
            task_id,

        "type":
            "xp",

        "target":
            target,

        "required":
            required,

        "progress":
            progress,
    }

    player[
        "main_quest"
    ] = main_quest


# =========================================================
# ДОДАТИ ЗАВЕРШЕНИЙ СТАН
# =========================================================

def add_completed_scene(
    player,
    scene_id
):

    main_quest = (
        player.get(
            "main_quest"
        )
        or {}
    )

    completed = (
        main_quest.get(
            "completed"
        )
        or []
    )

    if scene_id not in completed:

        completed.append(
            scene_id
        )

    main_quest[
        "completed"
    ] = completed

    player[
        "main_quest"
    ] = main_quest


