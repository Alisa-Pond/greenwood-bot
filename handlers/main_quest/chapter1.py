    # ПЕРШИЙ ЗАПУСК
    # =====================================================

    if not current_task:

        send_message_1(
            message
        )

        time.sleep(2)

        send_message_2(
            message
        )

        time.sleep(3)

        set_current_task(
            player,
            TASK_HEALTH,
            progress=0,
            required=HEALTH_TARGET_XP,
            target="health"
        )

        add_completed_scene(
            player,
            TASK_INTRO
        )

        save_main_quest(
            str(
                message.from_user.id
            ),
            player
        )

        send_message_3(
            message,
            player
        )

        return

    # =====================================================
    # ЗАВДАННЯ ЗДОРОВ'Я
    # =====================================================

    if current_task.get(
        "id"
    ) == TASK_HEALTH:

        send_message_3(
            message,
            player
        )

        return

    # =====================================================
    # СЦЕНА БЕАТРІЧЕ
    # =====================================================

    if current_task.get(
        "id"
    ) == TASK_BEATRICE:

        send_message_4(
            message
        )

        time.sleep(2)

        send_message_5(
            message
        )

        time.sleep(4)

        set_current_task(
            player,
            TASK_LEAF,
            progress=0,
            required=1,
            target="blue_leaf"
        )

        add_completed_scene(
            player,
            TASK_BEATRICE
        )

        save_main_quest(
            str(
                message.from_user.id
            ),
            player
        )

        send_message_6(
            message
        )

        return

    # =====================================================
    # СИНІЙ ЛИСТОК
    # =====================================================

    if current_task.get(
        "id"
    ) == TASK_LEAF:

        bot.send_message(
            message.chat.id,

            "🍃 <b>На кам'яній сходинці все ще лежить "
            "синій листок.</b>\n\n"

            "Марчелло чекає, поки ти вирішиш, "
            "що робити далі.",

            parse_mode="HTML",

            reply_markup=get_chapter_keyboard()
        )

        return


