# =========================================================
# ОТРИМАТИ XP СФЕРИ
# =========================================================

def get_sphere_xp(
    player,
    sphere_key
):

    spheres = (
        player.get("spheres")
        or {}
    )

    sphere = spheres.get(
        sphere_key
    )

    if not isinstance(
        sphere,
        dict
    ):

        return 0.0

    try:

        return float(
            sphere.get(
                "xp",
                0
            )
        )

    except (
        TypeError,
        ValueError
    ):

        return 0.0


